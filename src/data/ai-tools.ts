export type AIToolSlug = (typeof aiTools)[number]['slug'];
export type AITool = (typeof aiTools)[number];

export const toolBySlug = (slug: string) =>
  aiTools.find((tool) => tool.slug === slug);

export function localizeTool(tool: AITool, locale: 'ar' | 'en') {
  const ar = locale === 'ar';

  return {
    ...tool,
    displayTitle: ar ? tool.titleAr : tool.title,
    displayDescription: ar ? tool.descriptionAr : tool.description,
    displayCategory: ar ? tool.categoryAr : tool.category,
  };
}
